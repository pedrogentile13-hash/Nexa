/**
 * Simulados de vestibular da Grande criação 2: ENEM, Fuvest, Unicamp, Unesp, ITA e IME.
 * Questões AUTORAIS no estilo de cada banca (não são questões oficiais). ENEM segue só objetivo;
 * as 2ª fases têm discursivas corrigidas pela IA.
 */

const BANCA: Record<BancaG2, string> = {
  enem: 'ENEM',
  fuvest: 'Fuvest',
  unicamp: 'Unicamp',
  unesp: 'Unesp',
  ita: 'ITA',
  ime: 'IME',
};

function vest(
  slug: string,
  banca: BancaG2,
  subject: string,
  title: string,
  foco: string,
  questoes: QuestaoG2[],
): PacoteG2 {
  const disc = questoes.filter((q) => q.k === 'd').length;
  return {
    slug: `g2-vest-${slug}`,
    kind: 'simulado',
    context: 'vestibular',
    banca,
    subject,
    grade: '3ª série EM',
    title: `${BANCA[banca]} · ${title}`,
    subtitle: `${questoes.length} questões autorais no estilo ${BANCA[banca]}${disc ? ` (${disc} discursivas)` : ''}: ${foco}`,
    description: `Simulado de treino no estilo ${BANCA[banca]}, com questões autorais (não são da prova oficial). ${
      disc ? 'As discursivas são corrigidas pela IA com nota estimada. ' : ''
    }Use o quadro branco para rascunhar e confira a explicação de cada questão no fim.`,
    minutes: minutosSugeridos(questoes),
    questoes,
  };
}

/** Simulado com questões calculadas (5 alternativas). */
function gerado(
  slug: string,
  banca: BancaG2,
  subject: string,
  title: string,
  foco: string,
  gens: GenObj[],
  disc: GenDisc[] = [],
  n = 8,
): PacoteG2 {
  const r = rngFrom(`g2-vest/${slug}`);
  const objetivas = sortear(gens, r, n - disc.length, 4, slug.length % gens.length);
  return vest(slug, banca, subject, title, foco, [...objetivas, ...disc.map((g) => g(r))]);
}

